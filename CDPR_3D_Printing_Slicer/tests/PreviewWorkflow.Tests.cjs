'use strict';
const fs = require('fs');
const path = require('path');
const assert = require('assert/strict');
const { pathToFileURL } = require('url');
const { chromium } = require('playwright');

const html = path.resolve(process.argv[2] || '');
assert.ok(html.endsWith('.html') && fs.existsSync(html), 'Pass the cube HTML generated by SliceWorkflow.Tests.ps1.');
const project = path.resolve(__dirname, '..');
const evidence = path.join(project, 'build', 'offline', 'qa', 'stl-browser-' + Date.now());
fs.mkdirSync(evidence, { recursive: true });
const checks = [], errors = [], requests = [];
function pass(name, values = {}) { checks.push({ name, ...values }); console.log('PASS ' + name); }

(async () => {
  const context = await chromium.launchPersistentContext(path.join(evidence, 'edge-profile'), {
    executablePath: path.join(process.env['ProgramFiles(x86)'], 'Microsoft', 'Edge', 'Application', 'msedge.exe'),
    headless: true, viewport: { width: 1440, height: 1040 }, hasTouch: true,
    args: ['--no-first-run', '--disable-crash-reporter']
  });
  const page = await context.newPage();
  page.on('console', item => { if (['warning', 'error'].includes(item.type())) errors.push(item.text()); });
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => requests.push(request.url()));
  try {
    const begin = Date.now();
    await page.goto(pathToFileURL(html).href, { waitUntil: 'load' });
    await page.waitForFunction(() => document.querySelector('#plot').dataset.operation === '0');
    assert.equal(await page.title(), 'CDPR 3D simulator');
    assert.equal(await page.locator('#layer option').count(), 41);
    assert.equal(await page.locator('#cables .cable').count(), 8);
    assert.equal(await page.locator('#checks .passed').count(), 8);
    assert.match(await page.locator('#layerSummary').innerText(), /40 deposition heights/);
    pass('Real cube loads with 40 layers and model-bound cables', { load_ms: Date.now() - begin });

    await page.locator('#frame').selectOption('nozzle');
    await page.locator('#layer').selectOption('0');
    await page.waitForFunction(() => document.querySelector('#plot').dataset.layer === '0');
    const first = await page.locator('#plot').evaluate(node => ({ ...node.dataset }));
    assert.equal(first.playing, 'false');
    assert.ok(Number(first.depositSegments) > 20);
    await page.locator('#layer').selectOption('19');
    await page.waitForFunction(() => document.querySelector('#plot').dataset.layer === '19');
    const middle = await page.locator('#plot').evaluate(node => ({ ...node.dataset }));
    assert.ok(Number(middle.depositSegments) > Number(first.depositSegments));
    assert.match(await page.locator('#pose').innerText(), /0\.0050$/);
    await page.locator('#layer').selectOption('39');
    await page.waitForFunction(() => document.querySelector('#plot').dataset.layer === '39');
    const last = await page.locator('#plot').evaluate(node => ({ ...node.dataset }));
    assert.ok(Number(last.depositSegments) > Number(middle.depositSegments));
    assert.match(await page.locator('#pose').innerText(), /0\.0100$/);
    pass('Layer selection pauses and reveals the print up to the selected height', {
      first_deposits: +first.depositSegments, middle_deposits: +middle.depositSegments, final_deposits: +last.depositSegments
    });

    assert.ok(+last.travelSegments > 0);
    await page.locator('#showTravel').uncheck();
    await page.waitForFunction(() => document.querySelector('#plot').dataset.travelSegments === '0');
    assert.equal(await page.locator('#plot').getAttribute('data-deposit-segments'), last.depositSegments);
    await page.locator('#fitPath').click();
    await page.screenshot({ path: path.join(evidence, 'cube-print.png'), fullPage: true });
    await page.locator('#plane').selectOption('01');
    await page.screenshot({ path: path.join(evidence, 'cube-top.png'), fullPage: true });
    pass('Travel visibility preserves material deposition and path fitting');

    await page.locator('#plane').selectOption('3d');
    await page.locator('#reset').click();
    await page.locator('#speed').selectOption('10');
    await page.locator('#play').click();
    await page.waitForFunction(() => document.querySelector('#plot').dataset.waiting === 'true');
    assert.equal(await page.locator('#layer').inputValue(), 'all');
    const waitOne = await page.locator('#plot').getAttribute('data-operation');
    await page.locator('#play').click();
    await page.waitForFunction(previous => {
      const node = document.querySelector('#plot'); return node.dataset.waiting === 'true' && node.dataset.operation !== previous;
    }, waitOne);
    await page.locator('#play').click();
    await page.waitForFunction(() => +document.querySelector('#plot').dataset.operation > 12);
    await page.locator('#play').click();
    await page.waitForFunction(() => document.querySelector('#plot').dataset.playing === 'false');
    pass('Cube playback retains explicit temperature waits and pause controls');

    await page.locator('#layer').selectOption('39');
    const frameTimes = await page.evaluate(async () => {
      const result = []; let previous = performance.now();
      for (let i = 0; i < 24; i++) {
        document.querySelector('#showTravel').dispatchEvent(new Event('change'));
        await new Promise(requestAnimationFrame);
        const now = performance.now(); result.push(now - previous); previous = now;
      }
      return result;
    });
    frameTimes.sort((a, b) => a - b);
    pass('Full cube redraw timings recorded', { median_ms: frameTimes[12], p95_ms: frameTimes[22] });

    await page.locator('#frame').selectOption('end_effector');
    await page.locator('#fitRobot').click();
    await page.screenshot({ path: path.join(evidence, 'cube-robot.png'), fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.locator('#layer').selectOption('0');
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.screenshot({ path: path.join(evidence, 'cube-mobile.png'), fullPage: true });
    pass('Layer controls and robot view fit a 390 px mobile viewport');
    assert.deepEqual(errors, []);
    assert.deepEqual(requests.filter(url => !url.startsWith('file:')), []);
    pass('No console warnings, errors or external page requests');
  } finally {
    fs.writeFileSync(path.join(evidence, 'results.json'), JSON.stringify({ html, browser: context.browser()?.version(), checks, errors, requests }, null, 2));
    await context.close();
    console.log('Evidence: ' + evidence);
  }
})().catch(error => { console.error(error); process.exitCode = 1; });
